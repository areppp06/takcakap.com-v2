/// <reference lib="webworker" />

import { cleanupOutdatedCaches, precacheAndRoute, matchPrecache } from 'workbox-precaching';
import { registerRoute, NavigationRoute } from 'workbox-routing';

declare let self: ServiceWorkerGlobalScope;

// Clean up old caches
cleanupOutdatedCaches();

// Intercept navigation requests (HTML/page loads) to allow Cloudflare 502/503/504 maintenance pages to show,
// while still falling back to cached App Shell when completely offline.
// Register this first so it takes precedence over precached routes for navigation requests.
registerRoute(
    new NavigationRoute(async ({ request }) => {
        try {
            // Attempt to fetch from network first
            const response = await fetch(request);

            // If the server returns a 5xx error (including Cloudflare's 521, 522, etc.),
            // return the response directly so the browser displays the maintenance/error page.
            if (response.status >= 500 && response.status < 600) {
                return response;
            }

            // Handle Cloudflare redirects to maintenance pages
            if (response.type === 'opaqueredirect' || response.redirected) {
                return response;
            }

            // If the response is successful, serve it
            if (response.ok) {
                return response;
            }

            // Fallback to cached index.html for other errors
            const cachedResponse = await matchPrecache('/index.html');
            return cachedResponse || response;
        } catch (error) {
            // Only fall back to the offline cached app if the device itself is actually offline.
            // If the device is online but the connection was refused (e.g., local server killed), throw the error.
            if (!navigator.onLine) {
                const cachedResponse = await matchPrecache('/index.html');
                if (cachedResponse) {
                    return cachedResponse;
                }
            }
            throw error;
        }
    })
);

// Precache resources generated by vite-plugin-pwa (handles static assets offline-first)
precacheAndRoute(self.__WB_MANIFEST || []);

// Listen for push events
self.addEventListener('push', (event) => {
    let data = { title: 'New Notification', body: '', url: '/' };

    if (event.data) {
        try {
            data = event.data.json();
        } catch (e) {
            data.body = event.data.text();
        }
    }

    const options: NotificationOptions = {
        body: data.body,
        icon: '/pwa-192x192.png',
        badge: '/pwa-192x192.png',
        data: {
            url: data.url || '/'
        },
        // @ts-ignore: vibrate is valid for web notifications
        vibrate: [200, 100, 200]
    };

    event.waitUntil(
        self.registration.showNotification(data.title, options)
    );
});

// Handle notification click
self.addEventListener('notificationclick', (event) => {
    event.notification.close();

    const urlToOpen = event.notification.data.url || '/';

    event.waitUntil(
        self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((windowClients) => {
            // Check if there is already a window/tab open with the target URL
            for (let i = 0; i < windowClients.length; i++) {
                const client = windowClients[i];
                // If so, just focus it
                if (client.url.includes(urlToOpen) && 'focus' in client) {
                    return client.focus();
                }
            }
            // If not, open a new window/tab
            if (self.clients.openWindow) {
                return self.clients.openWindow(urlToOpen);
            }
        })
    );
});
